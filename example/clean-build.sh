#!/usr/bin/env bash
#
# Clean build of the example apps.
#
# Removes all generated / cached artifacts, reinstalls dependencies from the lockfiles and builds
# debug apps.
#
# Usage:
#   ./clean-build.sh [react-native|expo|all] [android|ios|all] [--no-build]
#
# Examples:
#   ./clean-build.sh                       # both apps, both platforms
#   ./clean-build.sh react-native ios      # bare React Native app, iOS only
#   ./clean-build.sh expo android --no-build
#
# Notes:
#   - Dependencies are installed with `npm ci` (exact lockfile versions). The SDK is installed from
#     its tarball URL, which each project allows through `allow-remote=root` in its .npmrc.
#   - Expo: android/ and ios/ are generated by `expo prebuild` and are deleted and regenerated.
#   - Builds are debug builds: Android `assembleDebug`, iOS for the simulator (no signing).
#   - Metro is not started. Stop any other Metro server on port 8081 before running the app.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

APP="all"
PLATFORM="all"
BUILD=1

for arg in "$@"; do
  case "$arg" in
    react-native | expo) APP="$arg" ;;
    android | ios) PLATFORM="$arg" ;;
    all) ;;
    --no-build) BUILD=0 ;;
    -h | --help)
      sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Unknown argument: $arg (use --help)" >&2
      exit 1
      ;;
  esac
done

# Two runs at the same time delete each other's node_modules / Pods mid-install. Allow only one.
LOCK_DIR="$ROOT/.clean-build.lock"
if ! mkdir "$LOCK_DIR" 2>/dev/null; then
  echo "Another clean-build.sh run is in progress (lock: $LOCK_DIR)." >&2
  echo "Wait for it to finish, or remove the lock directory if no run is active." >&2
  exit 1
fi
trap 'rmdir "$LOCK_DIR" 2>/dev/null || true' EXIT

wants_android() { [[ "$PLATFORM" == "all" || "$PLATFORM" == "android" ]]; }
wants_ios() { [[ "$PLATFORM" == "all" || "$PLATFORM" == "ios" ]]; }

step() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }

clean_js() {
  local dir="$1"
  step "[$(basename "$dir")] Removing node_modules and Metro caches"
  rm -rf "$dir/node_modules"
  rm -rf "${TMPDIR:-/tmp}"/metro-* "${TMPDIR:-/tmp}"/haste-map-* 2>/dev/null || true
  if command -v watchman >/dev/null 2>&1; then
    watchman watch-del "$dir" >/dev/null 2>&1 || true
  fi
}

install_js() {
  local dir="$1"
  step "[$(basename "$dir")] Installing dependencies (npm ci)"
  (cd "$dir" && npm ci --no-audit --no-fund)
}

build_android() {
  local dir="$1"
  step "[$(basename "$dir")] Building Android (assembleDebug)"
  (cd "$dir/android" && ./gradlew assembleDebug)
}

pod_install() {
  local dir="$1"
  step "[$(basename "$dir")] Installing pods"
  (cd "$dir/ios" && pod install)
}

build_ios() {
  local dir="$1"
  local workspace scheme
  workspace="$(find "$dir/ios" -maxdepth 1 -name '*.xcworkspace' | head -n 1)"
  if [[ -z "$workspace" ]]; then
    echo "No .xcworkspace found in $dir/ios (did pod install run?)" >&2
    exit 1
  fi
  scheme="$(basename "$workspace" .xcworkspace)"
  step "[$(basename "$dir")] Building iOS ($scheme, simulator)"
  xcodebuild \
    -workspace "$workspace" \
    -scheme "$scheme" \
    -configuration Debug \
    -sdk iphonesimulator \
    -destination 'generic/platform=iOS Simulator' \
    -derivedDataPath "$dir/ios/build/DerivedData" \
    build
}

clean_build_react_native() {
  local dir="$ROOT/react-native"

  clean_js "$dir"
  if wants_android; then
    step "[react-native] Removing Android build outputs"
    rm -rf "$dir/android/build" "$dir/android/app/build" "$dir/android/app/.cxx" "$dir/android/.gradle" "$dir/android/.kotlin"
  fi
  if wants_ios; then
    step "[react-native] Removing Pods, iOS build outputs and DerivedData"
    rm -rf "$dir/ios/Pods" "$dir/ios/build"
    rm -rf "$HOME/Library/Developer/Xcode/DerivedData"/StroeerExample-*
  fi

  install_js "$dir"
  wants_ios && pod_install "$dir"

  if [[ "$BUILD" == 1 ]]; then
    wants_android && build_android "$dir"
    wants_ios && build_ios "$dir"
  fi
  return 0
}

clean_build_expo() {
  local dir="$ROOT/expo"
  local prebuild_platform="$PLATFORM"

  clean_js "$dir"
  step "[expo] Removing generated native projects and .expo"
  rm -rf "$dir/.expo"
  wants_android && rm -rf "$dir/android"
  wants_ios && rm -rf "$dir/ios" "$HOME/Library/Developer/Xcode/DerivedData"/StroeerExampleExpo-*

  install_js "$dir"

  step "[expo] Generating native projects (expo prebuild --clean)"
  # --no-install: pods are installed below, so a failure is reported at that step.
  (cd "$dir" && CI=1 npx expo prebuild --clean --no-install --platform "$prebuild_platform")
  wants_ios && pod_install "$dir"

  if [[ "$BUILD" == 1 ]]; then
    wants_android && build_android "$dir"
    wants_ios && build_ios "$dir"
  fi
  return 0
}

if [[ "$APP" == "all" || "$APP" == "react-native" ]]; then
  clean_build_react_native
fi
if [[ "$APP" == "all" || "$APP" == "expo" ]]; then
  clean_build_expo
fi

step "Done"
